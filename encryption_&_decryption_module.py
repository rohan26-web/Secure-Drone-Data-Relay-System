from cryptography.fernet import Fernet

# Step 1: Generate encryption key
key = Fernet.generate_key()

# Save the key (acts as authentication key)
with open("secret.key", "wb") as key_file:
    key_file.write(key)

# Step 2: Read input data
message = input("Enter text to encrypt: ")

# Step 3: Encrypt data
fernet = Fernet(key)
encrypted_data = fernet.encrypt(message.encode())

# Step 4: Save encrypted data
with open("encrypted_data.txt", "wb") as enc_file:
    enc_file.write(encrypted_data)

print("\nEncryption Successful!")
print("Encrypted data saved as 'encrypted_data.txt'")
print("Key saved as 'secret.key'")


from cryptography.fernet import Fernet

# Step 1: Load key (authentication)
try:
    with open("secret.key", "rb") as key_file:
        key = key_file.read()
except FileNotFoundError:
    print("Authentication Failed: Key not found!")
    exit()

# Step 2: Load encrypted data
try:
    with open("encrypted_data.txt", "rb") as enc_file:
        encrypted_data = enc_file.read()
except FileNotFoundError:
    print("Encrypted file not found!")
    exit()

# Step 3: Decrypt
fernet = Fernet(key)
try:
    decrypted_data = fernet.decrypt(encrypted_data)
    print("\nDecryption Successful!")
    print("Original Message:", decrypted_data.decode())
except:
    print("Decryption Failed: Invalid Key!")

